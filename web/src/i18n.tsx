export type Lang = 'it' | 'en';
const dictionaries: Record<Lang, Record<Key, string>> = { en, it };

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  fmtDate: (iso: string | null | undefined) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem('hvp.lang');
    if (stored === 'it' || stored === 'en') return stored;
  } catch { /* storage unavailable */ }
  return navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const value = useMemo<I18n>(() => {
    const dict = dictionaries[lang];
    const dtf = new Intl.DateTimeFormat(lang === 'it' ? 'it-IT' : 'en-GB', { dateStyle: 'short', timeStyle: 'medium' });
    return {
      lang,
      setLang: (l) => {
        setLangState(l);
        document.documentElement.lang = l;
        try { localStorage.setItem('hvp.lang', l); } catch { /* ignore */ }
      },
      t: (key, vars) => {
        let s = dict[key] ?? key;
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
        return s;
      },
      fmtDate: (iso) => (iso ? dtf.format(new Date(iso)) : '—'),
    };
  }, [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider missing');
  return v;
}

